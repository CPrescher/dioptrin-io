use dioptrin_io::discovery::{self, Codec, Evidence};
#[test]
fn content_evidence_is_independent_of_optional_decoders() {
    for (bytes, codec) in [
        (&b"\x93NUMPY"[..], Codec::Npy),
        (b"II+\0", Codec::Tiff),
        (b"MM\0+", Codec::Tiff),
        (b"###CBF: VERSION", Codec::Cbf),
        (b"\xff\x4f\xff\x51", Codec::Jpeg2000),
        (b"P6\n", Codec::Pnm),
        (b"{\nHEADER_BYTES=512;", Codec::Dtrek),
        (b"{\nDim_1=2;", Codec::Edf),
    ] {
        let d = discovery::probe(bytes);
        assert_eq!(d.candidates.len(), 1);
        assert_eq!(d.candidates[0].codec, codec);
        assert_eq!(d.require_unique().is_ok(), codec.available());
    }
}
#[test]
fn unknown_weak_and_conflicting_evidence_never_choose_a_decoder() {
    assert!(discovery::probe(b"arbitrary source").candidates.is_empty());
    for bytes in [
        vec![0; 8192],
        b"# maybe a spreadsheet\n3 2\n1 2 3\n".to_vec(),
    ] {
        let d = discovery::probe(&bytes);
        assert_eq!(d.candidates[0].evidence, Evidence::AmbiguousHeader);
        assert!(d.require_unique().is_err());
    }
    let mut conflicting = vec![0; 512];
    conflicting[..6].copy_from_slice(b"\x93NUMPY");
    conflicting[208..212].copy_from_slice(b"MAP ");
    let d = discovery::probe(&conflicting);
    assert_eq!(d.candidates.len(), 2);
    assert!(d.require_unique().is_err());
    assert!(discovery::probe(b"P6not whitespace").candidates.is_empty());
}
#[test]
fn bounded_hdf5_user_blocks_and_short_prefixes() {
    for n in [512, 1024, 2048, 4096] {
        let mut b = vec![0; n + 8];
        b[n..].copy_from_slice(b"\x89HDF\r\n\x1a\n");
        assert_eq!(discovery::probe(&b).candidates[0].codec, Codec::Hdf5);
    }
    let mut b = vec![b'x'; 16392];
    b[16384..].copy_from_slice(b"\x89HDF\r\n\x1a\n");
    assert!(discovery::probe(&b).candidates.is_empty());
    for end in 0..6 {
        assert!(discovery::probe(&b"\x93NUMPY"[..end]).candidates.is_empty());
    }
}
#[test]
fn structured_fields_and_xml_markup_do_not_use_quoted_or_payload_text() {
    for bytes in [
        b"{\"data\":1}".as_slice(),
        b"{Description=HEADER_BYTES;}",
        b"{HEADER_BYTES_suffix=12;}",
    ] {
        let result = discovery::probe(bytes);
        assert!(result.require_unique().is_err());
        assert!(result.candidates.iter().all(|c| c.codec != Codec::Dtrek));
    }
    let conflict = discovery::probe(b"{ HEADER_BYTES = 512; Dim_1=2; }");
    assert_eq!(conflict.candidates.len(), 2);
    assert!(conflict.require_unique().is_err());
    for xml in [
        b"<!-- <array/> --> <unrelated/>".as_slice(),
        b"<unrelated note='<array/>'/>",
        b"<unrelated><![CDATA[<array/>]]></unrelated>",
        b"<!DOCTYPE unrelated [<!ELEMENT array ANY>]><unrelated/>",
        b"<array_not_a_tag/>",
    ] {
        assert!(discovery::probe(xml).candidates.is_empty(), "{xml:?}");
    }
    for xml in [
        b"<?xml version='1.0'?><array/>".as_slice(),
        b"\xef\xbb\xbf<ns:array xmlns:ns='urn:test'/>",
        b"<!-- comment --><XSDataImage/>",
    ] {
        let result = discovery::probe(xml);
        assert_eq!(result.candidates.len(), 1);
        assert_eq!(result.candidates[0].codec, Codec::Xsd);
    }
    assert!(
        discovery::probe(b"FORMAT arbitrary:86")
            .candidates
            .is_empty()
    );
    assert_eq!(
        discovery::probe(b"FORMAT :        86").candidates[0].codec,
        Codec::Bruker
    );
}
#[test]
fn mrc_map_disambiguates_the_small_dm3_version_prefix() {
    let mut header = vec![0; 1024];
    header[..4].copy_from_slice(&3u32.to_be_bytes());
    header[4..8].copy_from_slice(&32u32.to_be_bytes());
    header[8..12].copy_from_slice(&1u32.to_be_bytes());
    header[12..16].copy_from_slice(&2u32.to_be_bytes());
    header[208..212].copy_from_slice(b"MAP ");
    let result = discovery::probe(&header);
    assert_eq!(result.candidates.len(), 1);
    assert_eq!(result.candidates[0].codec, Codec::Mrc);
    header[208..212].fill(0);
    assert_eq!(discovery::probe(&header).candidates[0].codec, Codec::Dm3);
}

#[test]
fn edf_global_headers_have_positive_evidence_without_dimensions() {
    for prefix in [
        b"\r\n{\r\nEDF_DataFormatVersion = 2.10;".as_slice(),
        b"  { EDF_BinarySize = 0;",
        b"{\nEDF_HeaderSize = 512;",
        b"{\r\nEDF_DataBlocks = 1;",
    ] {
        let detection = discovery::probe(prefix);
        assert_eq!(detection.candidates.len(), 1);
        assert_eq!(detection.candidates[0].codec, Codec::Edf);
        assert_eq!(detection.candidates[0].evidence, Evidence::StructuredHeader);
    }
}

#[test]
fn cbf_versions_and_versionless_cif_binary_arrays_have_bounded_evidence() {
    for prefix in [
        b"###CBF: Version July 2008 generated by XDS\r\n".as_slice(),
        b"_array_data.data\r\n;\r\n--CIF-BINARY-FORMAT-SECTION--\r\n",
        b"# Generated by CIF.py\r\ndata_Pilatus1M\r\n_array_data.header_contents\r\n;\r\n# detector header\r\n;\r\n_array_data.data\r\n;\r\n--CIF-BINARY-FORMAT-SECTION--\r\n",
    ] {
        let detection = discovery::probe(prefix);
        assert_eq!(detection.candidates.len(), 1, "{prefix:?}");
        assert_eq!(detection.candidates[0].codec, Codec::Cbf);
    }
    for prefix in [
        b"###CBF: VERSIONED unrelated".as_slice(),
        b"data_ordinary\n_note 'CBF'\n",
        b"data_ordinary\n_note\n;\n_array_data.data\n;\n--CIF-BINARY-FORMAT-SECTION--\n",
        b"data_ordinary\n_array_data.data\n;\nordinary text\n",
        b"data_ordinary\n--CIF-BINARY-FORMAT-SECTION--\n",
        b"ordinary text\n_array_data.data\n;\n--CIF-BINARY-FORMAT-SECTION--\n",
        b"<document>\n_array_data.data\n;\n--CIF-BINARY-FORMAT-SECTION--\n</document>",
    ] {
        assert!(discovery::probe(prefix).candidates.is_empty(), "{prefix:?}");
    }
    let mut bounded = b"data_bounded\n_array_data.data\n;\n".to_vec();
    bounded.resize(discovery::PREFIX_BYTES, b' ');
    bounded.extend_from_slice(b"\n--CIF-BINARY-FORMAT-SECTION--\n");
    assert!(discovery::probe(&bounded).candidates.is_empty());
}

#[test]
fn mpa_declaration_can_follow_acquisition_fields_but_needs_adc_and_data() {
    let prefix =
        b"ctm=80\r\ndtm=400\r\nmpafmt=asc\r\n[ADC1]\r\nrange=1024\r\n[DATA0,1024 ]\r\n1842\r\n";
    let detection = discovery::probe(prefix);
    assert_eq!(detection.candidates.len(), 1);
    assert_eq!(detection.candidates[0].codec, Codec::Mpa);
    for prefix in [
        b"mpafmt=asc\n".as_slice(),
        b"mpafmt=asc\n[ADC1]\n",
        b"ctm=80\n[ADC1]\n[DATA0,1024 ]\n",
        b"ordinary text mpafmt=asc\n[ADC1]\n[DATA0,1024 ]\n",
        b"<document>\nmpafmt=asc\n[ADC1]\n[DATA0,1024 ]\n</document>",
        b"data_cif\n_note\n;\nmpafmt=asc\n[ADC1]\n[DATA0,1024 ]\n;\n",
    ] {
        assert!(discovery::probe(prefix).candidates.is_empty(), "{prefix:?}");
    }
}
