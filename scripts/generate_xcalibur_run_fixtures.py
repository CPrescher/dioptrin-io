"""Independent CC0 Xcalibur run records; no FabIO serialization is used.

Layout is the fixed public <Qd header after two raw256-byte text slots,
followed by declared <HHIddddddddHHHHd 88-byte sweeps. Reserved fields are
sentinels and every floating bit pattern is chosen explicitly.
"""
import hashlib
import json
import pathlib
import struct

ROOT = pathlib.Path(__file__).resolve().parents[1]
DESTINATION = ROOT / 'tests/data/xcalibur'
F64 = [0x8000000000000000, 0x3ff4000000000000, 0xc004000000000000,
       0x400c000000000000, 0x4012000000000000, 0x4016000000000000,
       0x3fb999999999999a, 0xbfd0000000000000, 0x4025000000000000]


def text(raw):
    if len(raw) > 256:
        raise ValueError('fixture text exceeds fixed slot')
    return raw + bytes(256 - len(raw))


def sweep(index, floats):
    # Pack float bits as integers to preserve signedzero/NaN payloads exactly.
    return (struct.pack('<HHI', index, 0xabcd, 0xfedcba98)
            + struct.pack('<8Q', *floats[:8]) + struct.pack('<4H', 0, 0xffff, 0x1234, 0x8000)
            + struct.pack('<Q', floats[8]))


def fixture():
    return (text(b'\0run_\xc3\xa4\0embedded') + text(b'/unavailable/original/output')
            + struct.pack('<QQ', 2, 0x8000000000000000)
            + sweep(7, F64) + sweep(0xffff, list(reversed(F64)))
            + b'opaque run trailer\0\xff')


def fixtures():
    source = fixture()
    edge = bytearray(source[:528 + 88])
    edge[:256] = bytes([0xff]) + bytes(255)
    struct.pack_into('<Q', edge, 512, 1)
    struct.pack_into('<Q', edge, 520, 0x7ff8000000000042)
    for index, bits in enumerate([1, 0x7ff0000000000000, 0xfff0000000000000,
                                  0x7ff8000000000042, 0x7ff0000000000001]):
        struct.pack_into('<Q', edge, 528 + 8 + index * 8, bits)
    return {'records.run': source, 'zero-sweeps.run': bytes(528), 'raw-text-floats.run': bytes(edge)}


def main():
    DESTINATION.mkdir(parents=True, exist_ok=True)
    records = []
    for name, payload in fixtures().items():
        (DESTINATION / name).write_bytes(payload)
        records.append({'path': name, 'bytes': len(payload), 'sha256': hashlib.sha256(payload).hexdigest()})
    provenance = {'schema': 1, 'license': 'CC0-1.0',
                  'origin': 'independently authored from the documented fixed-record layout; not generated by FabIO',
                  'generator': 'scripts/generate_xcalibur_run_fixtures.py',
                  'cases': 'all sweep fields, embedded/padded UTF8 text, unknown fields, signedzero, empty run, invalidUTF8, subnormal/infinity/NaN bits, opaque trailer',
                  'files': records}
    (DESTINATION / 'run-provenance.json').write_text(json.dumps(provenance, indent=2) + '\n')


if __name__ == '__main__':
    main()
